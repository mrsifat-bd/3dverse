// Writes the SQL for the Medical / Bones category split from
// src/lib/categorySplit.js (the single source of truth):
//   supabase/migration_category_split_1_apply.sql    run at launch, before the code goes live
//   supabase/migration_category_split_2_cleanup.sql  run after the new code is live
//   supabase/rollback_category_split.sql             puts every product back exactly as it was
// Usage: node scripts/gen-category-split-migration.mjs
import { writeFileSync } from 'fs'
import { OLD_CATEGORY, NEW_CATEGORIES, MEDICAL_PRODUCT_SLUGS } from '../src/lib/categorySplit.js'

const q = (s) => `'${String(s).replace(/'/g, "''")}'`
const medical = MEDICAL_PRODUCT_SLUGS.map(q).join(', ')
const BACKUP = 'public.category_split_backup_20261106'
const header = (title) => `-- =============================================================================
-- ${title}
-- GENERATED by scripts/gen-category-split-migration.mjs from src/lib/categorySplit.js.
-- Only the category of the "${OLD_CATEGORY}" products changes. No product is
-- created, deleted, duplicated or edited otherwise (prices, names, photos,
-- stock, IDs, reviews and orders are untouched).
-- =============================================================================
`

const apply = `${header('Category split, part 1 of 2: create Medical and Bones, move the products.')}
-- Safe while the OLD website code is still live: every moved product keeps the
-- old slug as an extra category until part 2, so the old page keeps working.
begin;

-- 1. Exact backup of every product that is touched (for the rollback).
create table if not exists ${BACKUP} (
  product_id uuid primary key,
  category text,
  category_id uuid,
  extra_categories text[],
  saved_at timestamptz not null default now()
);
alter table ${BACKUP} enable row level security;
revoke all on ${BACKUP} from public, anon, authenticated;
insert into ${BACKUP} (product_id, category, category_id, extra_categories)
select id, category, category_id, extra_categories from public.products
where category = ${q(OLD_CATEGORY)} or ${q(OLD_CATEGORY)} = any(extra_categories)
on conflict (product_id) do nothing;   -- a re-run keeps the ORIGINAL state

-- The products this run touches (for the checks in step 5).
create temporary table _split_touched on commit drop as
select id from public.products where category = ${q(OLD_CATEGORY)} or ${q(OLD_CATEGORY)} = any(extra_categories);

-- 2. The two new categories (English + Bangla), active.
insert into public.categories (name, name_bn, slug, blurb, status, sort) values
${NEW_CATEGORIES.map((c) => `  (${q(c.name)}, ${q(c.name_bn)}, ${q(c.slug)}, ${q(c.blurb)}, 'active', 1)`).join(',\n')}
on conflict (slug) do nothing;
update public.categories set status = 'active' where slug in (${NEW_CATEGORIES.map((c) => q(c.slug)).join(', ')});

-- 3. Main category: the listed products -> Medical, every other one -> Bones.
--    category_id follows when it pointed at the old category.
update public.products p set
  category = case when p.slug in (${medical}) then 'medical' else 'bones' end,
  category_id = case when p.category_id = (select id from public.categories where slug = ${q(OLD_CATEGORY)})
    then (select id from public.categories where slug = case when p.slug in (${medical}) then 'medical' else 'bones' end)
    else p.category_id end,
  -- old slug kept as an extra category until part 2 (old code keeps working)
  extra_categories = array_append(array_remove(coalesce(p.extra_categories, '{}'), ${q(OLD_CATEGORY)}), ${q(OLD_CATEGORY)})
where p.category = ${q(OLD_CATEGORY)};

-- 4. Products that had the old category only as an EXTRA one: same rule.
update public.products p set
  extra_categories = array_remove(array_remove(p.extra_categories, ${q(OLD_CATEGORY)}),
    case when p.slug in (${medical}) then 'medical' else 'bones' end)
    || array[case when p.slug in (${medical}) then 'medical' else 'bones' end, ${q(OLD_CATEGORY)}]
where p.category <> ${q(OLD_CATEGORY)} and ${q(OLD_CATEGORY)} = any(p.extra_categories)
  and p.category not in ('medical', 'bones');

-- 5. Checks: stop (and undo everything above) if anything is off.
do $$
declare moved int; med int; bon int; backed int; dup int;
begin
  select count(*) into backed from _split_touched t where exists (select 1 from ${BACKUP} b where b.product_id = t.id);
  select count(*) into moved from public.products p join _split_touched t on t.id = p.id where p.category in ('medical', 'bones') or p.extra_categories && array['medical', 'bones'];
  select count(*) into med from public.products where category = 'medical';
  select count(*) into bon from public.products where category = 'bones';
  select count(*) into dup from public.products where category in ('medical', 'bones') and category = any(extra_categories);
  if moved <> (select count(*) from _split_touched) or backed <> moved then raise exception 'split check: % touched, % backed up, % moved', (select count(*) from _split_touched), backed, moved; end if;
  if dup > 0 then raise exception 'split check: % products list their main category twice', dup; end if;
  if med <> ${MEDICAL_PRODUCT_SLUGS.length} then raise exception 'split check: expected ${MEDICAL_PRODUCT_SLUGS.length} Medical products, found %', med; end if;
  raise notice 'category split: % products moved (Medical %, Bones %)', moved, med, bon;
end $$;

commit;
`

const cleanup = `${header('Category split, part 2 of 2: retire the old category (after the new code is live).')}
-- The new code already redirects /category/${OLD_CATEGORY} to /category/bones and
-- never lists the old category. The old category row is kept (inactive), not deleted.
begin;
update public.products set extra_categories = array_remove(extra_categories, ${q(OLD_CATEGORY)})
where ${q(OLD_CATEGORY)} = any(extra_categories)
  and id in (select product_id from ${BACKUP});
update public.categories set status = 'inactive' where slug = ${q(OLD_CATEGORY)};
commit;
`

const rollback = `${header('ROLLBACK of the category split (parts 1 and 2).')}
-- Puts every moved product back exactly as it was (category, category_id,
-- extra categories) from ${BACKUP}, re-activates the old category and hides
-- Medical and Bones again (their rows are kept, nothing is deleted).
-- Then redeploy the previous website version.
begin;
update public.products p set
  category = b.category,
  category_id = b.category_id,
  extra_categories = b.extra_categories
from ${BACKUP} b where b.product_id = p.id;
update public.categories set status = 'active' where slug = ${q(OLD_CATEGORY)};
update public.categories set status = 'inactive' where slug in (${NEW_CATEGORIES.map((c) => q(c.slug)).join(', ')})
  and not exists (select 1 from public.products where category in (${NEW_CATEGORIES.map((c) => q(c.slug)).join(', ')}));
commit;
-- Keep ${BACKUP} until you are sure; drop it later by hand if you like.
`

writeFileSync(new URL('../supabase/migration_category_split_1_apply.sql', import.meta.url), apply)
writeFileSync(new URL('../supabase/migration_category_split_2_cleanup.sql', import.meta.url), cleanup)
writeFileSync(new URL('../supabase/rollback_category_split.sql', import.meta.url), rollback)
console.log('wrote 3 files')
